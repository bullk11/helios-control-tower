const MINUTE = 60_000;
const now = () => Date.now();

const service = (input: Partial<HeliosService> & { _id: string; ageMinutes: number }): HeliosService => {
  const { ageMinutes, ...rest } = input;
  const reference = now() - ageMinutes * MINUTE;
  return {
    created: reference,
    date: new Date(reference).toISOString(),
    status: SERVICE_STATUS.ACTIVE,
    ...rest,
  };
};

